//! System inventory: everything needed to rebuild the machine after a fresh
//! install (package lists, enabled services, disk layout). Written to a
//! directory that is backed up as `inventory.pxar`.

use std::fs;
use std::path::Path;
use std::process::{Command, Stdio};

use anyhow::{Context, Result};

/// (file name, program, arguments). Missing programs are skipped.
const COMMANDS: &[(&str, &str, &[&str])] = &[
    ("dpkg-selections.txt", "dpkg", &["--get-selections"]),
    ("apt-manual.txt", "apt-mark", &["showmanual"]),
    (
        "apt-sources.txt",
        "sh",
        &[
            "-c",
            "cat /etc/apt/sources.list /etc/apt/sources.list.d/* 2>/dev/null",
        ],
    ),
    (
        "flatpak-apps.txt",
        "flatpak",
        &["list", "--app", "--columns=application,origin,branch"],
    ),
    (
        "flatpak-remotes.txt",
        "flatpak",
        &["remotes", "--columns=name,url"],
    ),
    ("snap-list.txt", "snap", &["list"]),
    (
        "systemd-enabled.txt",
        "systemctl",
        &["list-unit-files", "--state=enabled", "--no-pager"],
    ),
    (
        "lsblk.json",
        "lsblk",
        &[
            "--json",
            "-o",
            "NAME,TYPE,SIZE,FSTYPE,UUID,PARTUUID,MOUNTPOINTS,MODEL",
        ],
    ),
    ("findmnt.json", "findmnt", &["--json", "--real"]),
    ("uname.txt", "uname", &["-a"]),
];

const FILES: &[(&str, &str)] = &[
    ("os-release", "/etc/os-release"),
    ("fstab", "/etc/fstab"),
    ("crypttab", "/etc/crypttab"),
];

pub struct InventoryReport {
    pub written: Vec<String>,
    pub skipped: Vec<String>,
}

pub fn generate(dir: &Path) -> Result<InventoryReport> {
    if dir.exists() {
        fs::remove_dir_all(dir).with_context(|| format!("cannot clean {}", dir.display()))?;
    }
    fs::create_dir_all(dir).with_context(|| format!("cannot create {}", dir.display()))?;
    let mut report = InventoryReport {
        written: Vec::new(),
        skipped: Vec::new(),
    };
    for (name, program, args) in COMMANDS {
        let output = Command::new(program)
            .args(*args)
            .stdin(Stdio::null())
            .stderr(Stdio::null())
            .env("LC_ALL", "C")
            .output();
        match output {
            Ok(out) if out.status.success() && !out.stdout.is_empty() => {
                fs::write(dir.join(name), &out.stdout)?;
                report.written.push((*name).to_string());
            }
            _ => report.skipped.push((*name).to_string()),
        }
    }
    for (name, source) in FILES {
        match fs::copy(source, dir.join(name)) {
            Ok(_) => report.written.push((*name).to_string()),
            Err(_) => report.skipped.push((*name).to_string()),
        }
    }
    // Machine-readable disk layout for the rescue stick.
    match crate::layout::capture().and_then(|l| Ok(serde_json::to_vec_pretty(&l)?)) {
        Ok(json) => {
            fs::write(dir.join(crate::layout::LAYOUT_FILE), json)?;
            report.written.push(crate::layout::LAYOUT_FILE.to_string());
        }
        Err(_) => report.skipped.push(crate::layout::LAYOUT_FILE.to_string()),
    }
    let boot_mode = if Path::new("/sys/firmware/efi").exists() {
        "uefi"
    } else {
        "bios"
    };
    fs::write(dir.join("boot-mode.txt"), format!("{boot_mode}\n"))?;
    report.written.push("boot-mode.txt".to_string());
    fs::write(
        dir.join("README.txt"),
        "Generated by nestegg before each backup.\n\
         Use these lists to reinstall packages and recreate the disk layout\n\
         after a fresh installation. See the nestegg restore documentation.\n",
    )?;
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_files_and_cleans_old_ones() {
        let dir = tempfile::tempdir().unwrap();
        let inv = dir.path().join("inventory");
        fs::create_dir_all(&inv).unwrap();
        fs::write(inv.join("stale.txt"), "old").unwrap();
        let report = generate(&inv).unwrap();
        assert!(!inv.join("stale.txt").exists());
        assert!(inv.join("README.txt").exists());
        assert!(inv.join("boot-mode.txt").exists());
        assert!(report.written.contains(&"uname.txt".to_string()));
    }
}
